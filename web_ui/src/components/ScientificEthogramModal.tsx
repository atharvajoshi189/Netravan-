import React, { useState } from 'react';
import {
  FileText,
  Download,
  Copy,
  Check,
  X,
  Activity,
  Compass,
  ScanEye,
  Shield,
  HeartPulse,
  Eye,
  Clock,
  Sparkles,
  MapPin,
  AlertCircle
} from 'lucide-react';

export interface ScientificEthogramData {
  report_id: string;
  protocol: string;
  subject_identity: string;
  demographics: string;
  camera_station: string;
  gps_coordinates: string;
  habitat: string;
  timestamp: string;
  posture: {
    title: string;
    category: string;
    confidence: string;
    biomechanics: string;
    head_cervical_angle: string;
  };
  behavior_activity: {
    title: string;
    category: string;
    confidence: string;
    detailed_notes: string;
    gaze_fixation: string;
  };
  aural_signals: {
    pinnae_state: string;
    auditory_tracking: string;
    vocalizations: string;
  };
  caudal_dynamics: {
    tail_carriage: string;
    ethological_significance: string;
  };
  body_condition: {
    bcs_rating: string;
    musculature: string;
    nutritional_state: string;
    injuries_audit: string;
  };
  anthropogenic_stress: {
    stress_index: string;
    distance_to_human_edge: string;
    safari_route_clearance: string;
    behavioral_reaction: string;
  };
  spatial_forecast: {
    primary_vector: string;
    probability_primary: string;
    secondary_vector: string;
    displacement_projection: string;
  };
  management_recommendations: string[];
}

interface ScientificEthogramModalProps {
  isOpen: boolean;
  onClose: () => void;
  ethogram: ScientificEthogramData;
  imageSrc?: string | null;
}

